#!/usr/bin/env node
// Qawwam: pull the disclosure documents from the API into the landing's content.
//
// The API is the source of truth for these documents — the app renders the same
// markdown from the same endpoint — so the landing no longer keeps a
// hand-maintained second copy of them. Run this when a document changes in
// qawwam-api, and commit what it writes:
//
//   npm run disclosures:sync     write src/content/ from the API
//   npm run disclosures:check    verify; non-zero exit if the tree is behind
//
// Only the three documents the API serves are generated. Account deletion has no
// endpoint, so src/content/account-deletion.md and its page stay hand-written.
//
// Needs API_TOKEN in the environment or in .env.local (gitignored — `*.local` is,
// `.env` is not). Dev and prod use *different* token values, and a token does not
// cross over, so the base has to match the token you have:
//
//   npm run disclosures:sync -- --base https://qawwam-api.hadiayo39.workers.dev

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)))
const CONTENT = join(ROOT, 'src/content')

const DEFAULT_BASE = 'https://qawwam-api-prod.hadiayo39.workers.dev'

const args = process.argv.slice(2)
const check = args.includes('--check')
const baseArg = args.indexOf('--base')
const BASE = (baseArg === -1 ? process.env.QW_API_BASE ?? DEFAULT_BASE : args[baseArg + 1]).replace(
  /\/$/,
  '',
)

/** The documents that come from the API, and the file each one is written to. */
const DOCUMENTS = [
  { slug: 'terms-of-use', file: 'terms.md' },
  { slug: 'privacy-policy', file: 'privacy.md' },
  { slug: 'acknowledgement', file: 'acknowledgement.md' },
]

function token() {
  if (process.env.API_TOKEN) return process.env.API_TOKEN
  try {
    for (const line of readFileSync(join(ROOT, '.env.local'), 'utf8').split('\n')) {
      const match = line.match(/^API_TOKEN=(.+)$/)
      if (match) return match[1].trim().replace(/^["']|["']$/g, '')
    }
  } catch {
    /* fall through */
  }
  throw new Error(
    'API_TOKEN not found. Put it in .env.local or the environment — see ' +
      'src/content/README.md. Dev and prod tokens are not interchangeable.',
  )
}

async function document(slug, auth) {
  const response = await fetch(`${BASE}/v1/disclosures/${slug}`, {
    headers: { Authorization: `Bearer ${auth}` },
  })

  if (response.status === 401) {
    throw new Error(
      `401 from ${BASE} for "${slug}". The API_TOKEN does not match this base — ` +
        'dev and prod each have their own.',
    )
  }
  if (!response.ok) {
    throw new Error(`${slug}: HTTP ${response.status} ${response.statusText}`)
  }

  const body = await response.json()
  const data = body?.data
  if (!data?.content || !data?.version || !data?.updatedAt || !data?.title) {
    throw new Error(`${slug}: unexpected response shape: ${JSON.stringify(body).slice(0, 200)}`)
  }
  return data
}

/**
 * The page renders its own heading, so the document's leading `# Title` is
 * dropped rather than shown twice. Nothing else is touched: what the app shows
 * and what the landing shows are the same markdown.
 */
function bodyOnly(content, title) {
  return content.replace(new RegExp(`^# ${title}\\n+`), '').trimEnd() + '\n'
}

/** The metadata the pages read, so version and date are stated once. */
function metadataModule(documents) {
  const entries = DOCUMENTS.map(({ slug }) => {
    const { title, version, updatedAt } = documents[slug]
    return `  '${slug}': { title: ${JSON.stringify(title)}, version: ${JSON.stringify(
      version,
    )}, updatedAt: ${JSON.stringify(updatedAt)} },`
  }).join('\n')

  return `// Generated by scripts/fetch-disclosures.mjs — do not edit by hand.
// Source: the API's /v1/disclosures/* endpoints. Refresh with \`npm run disclosures:sync\`.
// The base used is deliberately not recorded here: it is an environment, and
// recording it would make the file churn when the same documents are pulled
// from dev instead of prod.

export interface DisclosureMeta {
  title: string
  version: string
  updatedAt: string
}

export const disclosures = {
${entries}
} satisfies Record<string, DisclosureMeta>
`
}

const auth = token()
const documents = {}
for (const { slug } of DOCUMENTS) {
  documents[slug] = await document(slug, auth)
}

const wanted = [
  ...DOCUMENTS.map(({ slug, file }) => ({
    path: join(CONTENT, file),
    contents: bodyOnly(documents[slug].content, documents[slug].title),
  })),
  { path: join(CONTENT, 'disclosures.ts'), contents: metadataModule(documents) },
]

const stale = []
let written = 0

for (const { path, contents } of wanted) {
  let current = null
  try {
    current = readFileSync(path, 'utf8')
  } catch {
    /* not written yet */
  }

  if (current === contents) continue
  stale.push(path)

  if (check) continue
  writeFileSync(path, contents)
  written++
}

const name = (path) => relative(ROOT, path)

if (check) {
  if (stale.length === 0) {
    console.log(`OK — src/content matches ${BASE}.`)
    process.exit(0)
  }
  console.error(`BEHIND — ${stale.length} file(s) differ from ${BASE}:`)
  for (const path of stale) console.error(`  - ${name(path)}`)
  console.error('\nRun: npm run disclosures:sync')
  process.exit(1)
}

if (written === 0) {
  console.log(`Already current with ${BASE} — nothing written.`)
} else {
  for (const path of stale) console.log(`wrote ${name(path)}`)
  console.log(`\n${written} file(s) updated from ${BASE}. Commit them with the change.`)
}
